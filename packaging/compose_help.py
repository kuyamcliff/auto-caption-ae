"""Pads the raw Help screenshots with side gutters and writes arrow data.

python compose_help.py <rawDir> <extensionDir>
"""
import json, sys, os
from PIL import Image, ImageDraw

raw, ext = sys.argv[1], sys.argv[2]
S = 2                # device scale of the raw shots
G = 44 * S           # gutter width
P = 10 * S           # top / bottom padding
BG = (10, 10, 10)
targets = json.load(open(os.path.join(raw, 'targets.json')))
out = {}
for name, rects in targets.items():
    im = Image.open(os.path.join(raw, name + '.png')).convert('RGB')
    w, h = im.size
    W, H = w + 2 * G, h + 2 * P
    c = Image.new('RGB', (W, H), BG)
    c.paste(im, (G, P))
    d = ImageDraw.Draw(c)
    d.rectangle([G - 1, P - 1, G + w, P + h], outline=(46, 46, 46))
    c = c.resize((W * 3 // 4, H * 3 // 4), Image.LANCZOS)   # 1.5x is sharp enough
    c.save(os.path.join(ext, 'help', name + '.png'), optimize=True)
    arrows = []
    for i, r in enumerate(rects):
        if not r:
            raise SystemExit('missing target %s #%d' % (name, i + 1))
        cy = (P + (r['y'] + r['h'] / 2) * S) / H * 100
        cx = r['x'] + r['w'] / 2
        if cx >= r['vw'] / 2:
            tx = (G + (r['x'] + r['w'] - 6) * S) / W * 100
            fx = (W - G / 2) / W * 100
        else:
            tx = (G + (r['x'] + 6) * S) / W * 100
            fx = (G / 2) / W * 100
        arrows.append({'n': i + 1, 'from': [round(fx, 2), round(cy, 2)], 'to': [round(tx, 2), round(cy, 2)]})
    out[name] = arrows

js = ('/* Generated by packaging/compose_help.py from the Help screenshots. */\n'
      '(function (root) { root.CQ = root.CQ || {}; root.CQ.helpArrows = ' + json.dumps(out) + '; })(typeof window !== \'undefined\' ? window : global);\n')
open(os.path.join(ext, 'js', 'ui', 'help-arrows.js'), 'w').write(js)
print('ok', ', '.join('%s:%d' % (k, len(v)) for k, v in out.items()))
